function stableIndex(seed: string, length: number) {
  let hash = 2_166_136_261;
  for (const character of seed) { hash ^= character.charCodeAt(0); hash = Math.imul(hash, 16_777_619); }
  return (hash >>> 0) % length;
}

function hasFinalConsonant(value: string) {
  const last = [...value.trim()].at(-1);
  if (!last) return false;
  const code = last.charCodeAt(0) - 0xac00;
  return code >= 0 && code <= 11_171 && code % 28 !== 0;
}

const withJosa = (value: string, consonant: string, vowel: string) => `${value}${hasFinalConsonant(value) ? consonant : vowel}`;
const sentence = (value: string) => /[.!?…]$/u.test(value.trim()) ? value.trim() : `${value.trim()}.`;
function withRoleParticle(value: string) {
  const last = [...value.trim()].at(-1);
  if (!last) return `${value}로`;
  const code = last.charCodeAt(0) - 0xac00;
  const finalConsonant = code >= 0 && code <= 11_171 ? code % 28 : 0;
  return `${value}${finalConsonant === 0 || finalConsonant === 8 ? '로' : '으로'}`;
}

function itemAt<T>(items: readonly T[], seed: string, excluded = new Set<string>(), key: (item: T) => string = String) {
  const candidates = items.filter((item) => !excluded.has(key(item)));
  return candidates[stableIndex(seed, candidates.length)]!;
}

function context(core: ResultCore) {
  const setting = historicalSettings.find(({ id }) => id === core.locationId);
  const occupationId = occupationAliases[core.occupationId] ?? core.occupationId;
  const occupation = historicalOccupations.find(({ id }) => id === occupationId);
  if (!setting || !occupation) throw new Error(`Unknown story context: ${core.locationId}/${core.occupationId}`);
  return { setting, occupation };
}

export function storyDiversityCounts() {
  return {
    childhoodPerSetting: childhoodPatterns.length,
    workPerOccupation: workPatterns.length,
    turningTypes: turningTypes.length,
    variantsPerTurningType: sceneVariants.length,
    relationshipPerType: Math.min(...Object.values(relationshipActions).map(({ length }) => length)),
    costs: costs.length,
    aftermaths: aftermaths.length,
  };
}

export function selectDiverseLifeEvents(core: ResultCore): { childhood: DiverseStoryEvent; work: DiverseStoryEvent; turning: DiverseStoryEvent } {
  const { setting, occupation } = context(core);
  const root = `${core.answerHash}:${core.recordNo}:${core.locationId}:${core.occupationId}:${core.eventId}:${core.relationshipId}`;
  const relationCandidates = relationshipActions[core.relationshipId] ?? relationshipActions.REL_COMPANION!;
  const usedThemes = new Set<string>();

  const childhoodPattern = itemAt(childhoodPatterns, `${root}:childhood`);
  usedThemes.add(childhoodPattern[0]);
  const childhoodNote = itemAt(setting.dailyLifeNotes, `${root}:childhood-note`);
  const childhood: DiverseStoryEvent = {
    id: `${setting.id}_CHILD_${childhoodPattern[0]}`,
    theme: childhoodPattern[0], title: childhoodPattern[1], problem: childhoodPattern[2],
    setup: `${setting.label}에서 자라던 어린 시절이었습니다. ${sentence(childhoodNote)} 그러던 어느 날, ${childhoodPattern[2]}.`,
    choice: childhoodPattern[3], cost: itemAt(childhoodCosts, `${root}:childhood-cost`),
    relationshipAction: '곁에 있던 어른은 결과를 대신 만들지 않고 당신이 선택을 끝까지 설명하도록 기다렸습니다',
    consequence: childhoodConsequenceByTheme[childhoodPattern[0]] ?? itemAt(childhoodAfters, `${root}:childhood-aftermath`), timeAfter: itemAt(timeAfters, `${root}:childhood-time`),
    legacy: '이 경험은 잘못을 보았을 때 모른 척하지 않는 태도로 남았습니다',
  };

  const workPattern = itemAt(workPatterns, `${root}:work`, usedThemes, (item) => item[0]);
  usedThemes.add(workPattern[0]);
  const action = itemAt(occupation.dailyActions, `${root}:work-action`);
  const object = itemAt(occupation.signatureObjects, `${root}:work-object`);
  const work: DiverseStoryEvent = {
    id: `${occupation.id}_WORK_${workPattern[0]}`,
    theme: workPattern[0], title: workPattern[1], problem: workPattern[2],
    setup: `${setting.label}에서 ${withRoleParticle(occupation.label)} 일하며 ${sentence(action)} ${withJosa(object, '을', '를')} 사용하던 어느 날, ${workPattern[2]}.`,
    choice: workPattern[3], cost: itemAt(workCosts, `${root}:work-cost`),
    relationshipAction: itemAt(relationCandidates, `${root}:work-relation`),
    consequence: itemAt(aftermaths, `${root}:work-aftermath`), timeAfter: itemAt(timeAfters, `${root}:work-time`),
    legacy: `그 뒤 ${occupation.label}의 일에는 결과뿐 아니라 과정과 안전을 확인하는 순서가 남았습니다`,
  };

  const turningType = itemAt(turningTypes, `${root}:${core.eventId}:turning`, usedThemes, (item) => item[0]);
  const variant = itemAt(sceneVariants, `${root}:turning-variant`);
  const turningNote = itemAt(setting.dailyLifeNotes, `${root}:turning-note`);
  const turning: DiverseStoryEvent = {
    id: `${setting.id}_TURN_${turningType[0]}_${sceneVariants.indexOf(variant) + 1}`,
    theme: turningType[0], title: turningType[1], problem: turningType[2],
    setup: `${variant[0]}, ${setting.label}에서 ${sentence(variant[1])} ${turningType[2]}. ${sentence(turningNote)}`,
    choice: turningChoiceByTheme[turningType[0]] ?? `당신은 ${withJosa(occupation.signatureObjects[stableIndex(`${root}:turning-object`, occupation.signatureObjects.length)]!, '만', '만')} 챙기지 않고 피해가 가장 큰 사람을 먼저 확인한 뒤 역할을 나누었습니다`,
    cost: itemAt(costs, `${root}:turning-cost`), relationshipAction: itemAt(relationCandidates, `${root}:turning-relation`),
    consequence: itemAt(aftermaths, `${root}:turning-aftermath`), timeAfter: itemAt(timeAfters, `${root}:turning-time`),
    legacy: `${setting.label}에서 비슷한 위기에 대비하는 새로운 기준으로 자리 잡았습니다`,
  };

  return { childhood, work, turning };
}
