const replacementManuscriptById = new Map(
  replacementStoryManuscripts.map((manuscript) => [manuscript.id, manuscript]),
);

export const storyManuscripts: readonly StoryManuscript[] = originalStoryManuscripts.map(
  (manuscript) => replacementManuscriptById.get(manuscript.id) ?? manuscript,
);

export function findStoryManuscript(id: string): StoryManuscript | undefined {
  return storyManuscripts.find((manuscript) => manuscript.id === id);
}

export function renderStoryEpisode(manuscript: StoryManuscript, signal: StorySignal): string {
  const moment = manuscript.episode.signalMoments[signal];
  if (!moment) throw new Error(`Missing manuscript signal moment: ${manuscript.id}/${signal}`);
  return [manuscript.episode.beforeSignal, moment, manuscript.episode.afterSignal].join('\n\n');
}

export function renderStoryIdentity(manuscript: StoryManuscript, name: string): string {
  const { era, region, gender, birthYear, deathYear, summary } = manuscript.identity;
  return `${name} · ${gender}\n${era} · ${region}\n${birthYear}~${deathYear}\n\n${summary}`;
}

export function renderStoryTimeline(manuscript: StoryManuscript): string {
  return manuscript.timeline.map(({ when, event }) => `${when} · ${event}`).join('\n');
}

export function renderStoryMemories(manuscript: StoryManuscript): string {
  return manuscript.memories.map(({ label, detail }) => `${label}\n${detail}`).join('\n\n');
}
