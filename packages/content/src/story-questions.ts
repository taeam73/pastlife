import type { CoreTag, Question, Stage, StorySignal } from './types.js';

const tagsBySignal: Record<StorySignal, CoreTag> = {
  notice: 'knowledge', connect: 'connection', rest: 'calm', explore: 'adventure',
  repair: 'creativity', speak: 'courage', protect: 'protection', release: 'freedom',
};

type Option = readonly [text: string, signal: StorySignal];

function scene(stage: Stage, number: number, text: string, options: readonly [Option, Option, Option, Option, Option, Option]): Question {
  const id = `SQ${stage}_${String(number).padStart(2, '0')}`;
  return {
    id, stage, text,
    choices: options.map(([choiceText, signal], index) => ({
      id: `${id}_C${index + 1}`, text: choiceText, displayOrder: index + 1,
      tagScores: [{ tag: tagsBySignal[signal], score: 2 }], axisScores: [], storySignals: [signal],
    })),
  };
}

